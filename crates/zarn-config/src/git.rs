fn attribution(line: &str) -> bool {
    let lower = line.trim().to_lowercase();
    lower.starts_with("co-authored-by:")
        || lower.starts_with("signed-off-by:")
        || lower.contains("generated with")
        || lower.contains("generated by")
}

pub fn clean_message(raw: &str, trailer: Option<&str>) -> String {
    let text = raw.trim();
    let text = text
        .strip_prefix("```")
        .map(|rest| rest.trim_start_matches(|c: char| c.is_ascii_alphanumeric()).trim_end_matches("```"))
        .unwrap_or(text);
    let mut lines: Vec<&str> = text.lines().filter(|l| !attribution(l)).collect();
    while lines.last().is_some_and(|l| l.trim().is_empty()) {
        lines.pop();
    }
    let mut message = lines.join("\n").trim().to_string();
    if let Some(trailer) = trailer.map(str::trim).filter(|t| !t.is_empty()) {
        message.push_str("\n\n");
        message.push_str(trailer);
    }
    redact(&message)
}

pub fn clip(diff: &str) -> String {
    if diff.chars().count() <= DIFF_CHARS {
        return diff.to_string();
    }
    let kept: String = diff.chars().take(DIFF_CHARS).collect();
    format!("{kept}\n[diff cut at {DIFF_CHARS} characters]")
}

pub async fn draft(provider: &dyn Provider, model: &str, instruction: &str, material: &str) -> Result<String, String> {
    let mut request = Request::new(model, vec![Message::System(instruction.to_string()), Message::user(clip(material))]);
    request.max_tokens = 1024;
    request.temperature = 0.2;
    let run = async {
        let mut stream = provider.stream(request).await.map_err(|e| e.to_string())?;
        let mut text = String::new();
        while let Some(event) = stream.next().await {
            match event {
                Event::TextDelta(delta) => text.push_str(&delta),
                Event::Error(err) => return Err(err.to_string()),
                Event::Done(_) => break,
                _ => {}
            }
        }
        Ok(text)
    };
    match tokio::time::timeout(TIMEOUT, run).await {
        Ok(Ok(text)) if !text.trim().is_empty() => Ok(text),
        Ok(Ok(_)) => Err("the model returned an empty draft".into()),
        Ok(Err(err)) => Err(redact(&err)),
        Err(_) => Err("the draft timed out".into()),
    }
}

async fn git(cwd: &std::path::Path, args: &[&str]) -> Result<(bool, String), String> {
    let output = tokio::process::Command::new("git")
        .arg("--no-pager")
        .args(args)
        .current_dir(cwd)
        .stdin(std::process::Stdio::null())
        .output()
        .await
        .map_err(|e| format!("could not run git: {e}"))?;
    let text = if output.status.success() { output.stdout } else { output.stderr };
    Ok((output.status.success(), String::from_utf8_lossy(&text).into_owned()))
}

pub async fn working_diff(cwd: &std::path::Path, path: &str) -> Result<String, String> {
    let (inside, _) = git(cwd, &["rev-parse", "--is-inside-work-tree"]).await?;
    if !inside {
        return Err("this folder is not a git repository".into());
    }
    let (has_head, _) = git(cwd, &["rev-parse", "--verify", "--quiet", "HEAD"]).await?;
    let base = if has_head {
        "HEAD".to_string()
    } else {
        git(cwd, &["hash-object", "-t", "tree", "--stdin"]).await?.1.trim().to_string()
    };
    let mut args = vec!["diff", "--no-color", "--no-ext-diff", base.as_str()];
    if !path.is_empty() {
        args.extend(["--", path]);
    }
    let (ok, diff) = git(cwd, &args).await?;
    if !ok {
        return Err(diff.trim().to_string());
    }
    let mut listing = vec!["ls-files", "--others", "--exclude-standard"];
    if !path.is_empty() {
        listing.extend(["--", path]);
    }
    let (_, untracked) = git(cwd, &listing).await?;
    let untracked: Vec<&str> = untracked.lines().filter(|l| !l.trim().is_empty()).collect();
    let mut text = diff.trim_end().to_string();
    if !untracked.is_empty() {
        if !text.is_empty() {
            text.push_str("\n\n");
        }
        text.push_str(&format!("untracked ({}):\n", untracked.len()));
        text.push_str(&untracked.iter().map(|f| format!("  {f}")).collect::<Vec<_>>().join("\n"));
    }
    if text.is_empty() {
        text = "no changes since the last commit".into();
    }
    Ok(redact(&text))
}

pub fn split_pr(raw: &str) -> (String, String) {
    let text = clean_message(raw, None);
    let mut lines = text.lines();
    let title = lines
        .next()
        .unwrap_or_default()
        .trim()
        .trim_start_matches(['#', ' '])
        .trim_start_matches("Title:")
        .trim()
        .to_string();
    let body = lines.collect::<Vec<_>>().join("\n").trim().to_string();
    (title, body)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn attribution_lines_are_dropped_unless_configured() {
        let raw = "Fix the parser\n\nHandle empty input.\n\nCo-Authored-By: Bot <bot@example.test>\nGenerated with SomeTool\n";
        assert_eq!(clean_message(raw, None), "Fix the parser\n\nHandle empty input.");
        assert_eq!(
            clean_message(raw, Some("Reviewed-by: Me <me@example.test>")),
            "Fix the parser\n\nHandle empty input.\n\nReviewed-by: Me <me@example.test>"
        );
        assert_eq!(clean_message("```text\nAdd x\n```", None), "Add x");
    }

    #[test]
    fn pr_drafts_split_into_title_and_body() {
        let (title, body) = split_pr("Title: Add the parser\n\n## Summary\nIt parses.");
        assert_eq!(title, "Add the parser");
        assert_eq!(body, "## Summary\nIt parses.");
    }
}
